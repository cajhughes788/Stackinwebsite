// Fingerprints every file in public/media and public/images into lib/media-versions.ts,
// so pages can ask for "/media/journey/c6.mp4?v=<hash>" (lib/media.ts). A replaced file
// gets a new address, and no browser or CDN keeps showing the old one (sites-engine
// LESSONS: "A replaced clip kept playing the old one"). Runs before every build and dev.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = {};
for (const dir of ["media", "images"]) {
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (!e.name.startsWith(".")) out["/" + path.relative(path.join(root, "public"), p)] = crypto.createHash("sha1").update(fs.readFileSync(p)).digest("hex").slice(0, 8);
    }
  };
  const d = path.join(root, "public", dir);
  if (fs.existsSync(d)) walk(d);
}
const sorted = Object.fromEntries(Object.entries(out).sort());
const ts = `// Generated by scripts/media-versions.mjs before every build. Do not edit by hand.\nexport const MEDIA_VERSIONS: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`;
const file = path.join(root, "lib", "media-versions.ts");
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== ts) fs.writeFileSync(file, ts);
console.log(`media-versions: ${Object.keys(sorted).length} files`);
